print('Salut ! Testons le condition if en python')
choix = input('Choisir entre O ou N :')

if choix == 'O' :
    print("c'est le texte qui indique que vous avez choisie O")
    print('fin !')
if choix == 'N' :
    print("c'est le texte qui indique que vous avez choisie N")
    print('fin !')
else :
    print("Soit O ou N pas autre chose imbecile")
    print('fin !')